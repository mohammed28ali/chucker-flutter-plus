/// Route name definitions used throughout the network inspector.
abstract final class Routes {
  /// Initial / main inspector list route.
  static const String initialRoute = '/';

  /// Network inspector list page.
  static const String networkInspector = '/network-inspector';

  /// Detailed view for a specific network transaction.
  static const String requestDetail = '/request-detail';

  /// Inspector preferences and settings page.
  static const String settings = '/settings';

  /// Full-screen media preview page.
  static const String mediaPreview = '/media-preview';
}
